    protected const DAYS = [
        'en' => ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'],
        'fr' => ['dim.', 'lun.', 'mar.', 'mer.', 'jeu.', 'ven.', 'sam.'],
    ];
    protected const MONTHS = [
        'en' => ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'],
        'fr' => ['janv.', 'févr.', 'mars', 'avr.', 'mai', 'juin', 'juil.', 'août', 'sept.', 'oct.', 'nov.', 'déc.'],
    ];

    public function __construct(public readonly string $lang = 'en')
    {
    }

    public static function for(?string $lang): self
    {
        return new self(in_array($lang, self::LANGS, true) ? $lang : 'en');
    }

    public function get(string $key, array $replace = []): string
    {
        $text = ($this->lang === 'fr' ? self::FR : self::EN)[$key] ?? self::EN[$key] ?? $key;
        foreach ($replace as $k => $v) {
            $text = str_replace('{' . $k . '}', (string)$v, $text);
        }
        return $text;
    }

    public function __invoke(string $key, array $replace = []): string
    {
        return $this->get($key, $replace);
    }

    /** "Tue 2 Dec" / "mar. 2 déc." */
    public function day(Carbon $date): string
    {
        return self::DAYS[$this->lang][$date->dayOfWeek] . ' ' . $date->day . ' ' . self::MONTHS[$this->lang][$date->month - 1];
    }

    /** "Tue 2 Dec 06:00" */
    public function when(Carbon $at): string
    {
        return $this->day($at) . ' ' . $at->format('H:i');
    }

    public function money(float|int|null $amount): string
    {
        return number_format((float)$amount, 0, ',', ' ') . ' FCFA';
    }

    public function classLabel(?string $class): string
    {
        return in_array($class, ['classic', 'vip', 'executive'], true) ? $this->get($class) : (string)$class;
    }
